#ifndef __UI_APP_H__
#define __UI_APP_H__

#include "linkqueue.h"

/*------------------------------------------------------------------
 * LVGL 显示界面（framebuffer + 触摸屏）
 *
 * 界面分四级（对应简历里说的"四级界面数据反馈"）：
 *   1. 实时参数：电压/电流/温度/湿度/烟雾/电量/健康度 大字号卡片
 *   2. 动态曲线：电压、电流各一条 120 点滚动曲线
 *   3. 参数配置：6 个阈值可现场上下调整，保存后写回配置文件
 *   4. 历史数据：从 SQLite 读最近记录，5 秒刷新一次
 *
 * 线程模型：
 *   ui_data 是邮箱系统里的第 6 个消费者，get_data -> alarm_data -> ui_data。
 *   LVGL 不是线程安全的，所以所有 lv_* 调用都只在这一个线程里发生，
 *   外面只管往队列里丢 msgdata，不碰任何控件。
 *----------------------------------------------------------------*/

/* 界面线程入口，注册到邮箱系统时名字用 "ui_data" */
void *ui_app_thread(void *arg);

/* 1 = 配置里开着界面且屏幕可用 */
int   ui_app_ready(void);

#endif
