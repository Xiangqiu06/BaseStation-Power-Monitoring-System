#ifndef __BSP_DS18B20_H__
#define __BSP_DS18B20_H__

#include <stdint.h>

/*------------------------------------------------------------------
 * DS18B20 单总线温度传感器（PB12）
 *
 * 电池柜的温度用 DS18B20：单总线只要一根线，几个传感器可以挂在
 * 同一根线上（靠 64 位 ROM 地址区分），布线比 I2C 省事。
 * 这里只做单点读取（跳过 ROM 命令），接线简单、代码也清楚。
 *
 * 时序全靠 DWT 周期计数器算，比空循环准：
 * 1-Wire 的复位脉冲要求 480us，写 1 的窗口只有 15us，
 * 用不准的延时会出现"有时读得到、有时读 85℃"的经典症状。
 *----------------------------------------------------------------*/

void  bsp_ds18b20_init(void);

/* 触发一次转换（12 位精度要 750ms，调用后别马上读） */
void  bsp_ds18b20_start_convert(void);

/* 读温度，返回 0 成功（℃），-1 表示没检测到器件（读回 85 或者全 1） */
int   bsp_ds18b20_read(float *temp_c);

/* 一次搞定：触发 + 等待 + 读取。阻塞 750ms 左右，别在高优先级任务里调 */
int   bsp_ds18b20_read_blocking(float *temp_c);

/* 微秒级延时（DWT 实现） */
void  bsp_delay_us(uint32_t us);

#endif
